import AppKit

@available(macOS 14.0, *)
@MainActor
final class ClipboardWatcher {
    private let store: ClipboardStore
    private var timer: Timer?
    private var nextMaintenance = Date.distantPast
    private let pasteboard: NSPasteboard
    private var lastChangeCount: Int

    init(store: ClipboardStore, pasteboard: NSPasteboard = .general) {
        self.store = store
        self.pasteboard = pasteboard
        self.lastChangeCount = pasteboard.changeCount
    }

    func start() {
        timer?.invalidate()
        let newTimer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            Task { @MainActor in
                self?.checkPasteboard()
            }
        }
        timer = newTimer
        RunLoop.main.add(newTimer, forMode: .common)
    }

    deinit { timer?.invalidate() }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func checkPasteboard() {
        let now = Date()
        if now >= nextMaintenance {
            store.applyRetention(now: now)
            nextMaintenance = now.addingTimeInterval(60)
        }
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        // Honor the NSPasteboard.org privacy conventions used by password managers.
        let excludedTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                             "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
                             "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
                             "Pasteboard generator type"].map { NSPasteboard.PasteboardType($0) }
        guard pasteboard.availableType(from: excludedTypes) == nil,
              let text = pasteboard.string(forType: .string) else { return }
        store.add(text: text)
    }
}
